//
//  1. NO TOKEN APPEARS TWICE. A repeat renders as a duplicate cell in the grid.
//  2. NO KEYWORD HAS TWO OWNERS. Ties are broken by catalog order, so a shared
//     keyword silently resolves to whichever group comes first — which is how
//     "docker" once landed on a generic package box instead of the whale.
//
// Rule 2 is why the Brands group owns every PRODUCT name while the Creatures
// group keeps only the CREATURE names: typing "docker" gets you the Docker
// mark, and 🐳 is still there for anyone who just wants a whale.

