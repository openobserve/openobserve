import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.A11Y_BASE_URL || 'http://localhost:5080/web';
const [STATE, OUT] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, storageState: STATE });
const p = await ctx.newPage();
await p.goto(BASE + '/');
await p.waitForTimeout(8000);
console.log('landed', p.url().replace(/\?.*/,''), 'q=', new URL(p.url()).searchParams.get('org_identifier'), 'title', await p.title());
const routes = await p.evaluate(() => { const app = document.querySelector('#app').__vue_app__; const r = app.config.globalProperties.$router; return r.getRoutes().map(x => ({ path: x.path, name: typeof x.name === 'symbol' ? String(x.name) : x.name, redirect: !!x.redirect, children: x.children?.length||0 })); });
fs.writeFileSync(OUT + '/runtime-routes.json', JSON.stringify(routes, null, 1));
console.log('routes', routes.length);
const nav = await p.evaluate(() => [...document.querySelectorAll('nav a, [role=navigation] a, aside a, a[href*="/web/"]')].map(a => `${a.getAttribute('href')} | ${(a.getAttribute('aria-label')||a.innerText||'').trim().replace(/\s+/g,' ').slice(0,40)} | ${a.getAttribute('data-test')||''}`));
console.log([...new Set(nav)].join('\n'));
await p.screenshot({ path: OUT + '/home-initial.png' });
const store = await p.evaluate(() => { const s = document.querySelector('#app').__vue_app__.config.globalProperties.$store; return { org: s.state.selectedOrganization?.identifier, orgs: (s.state.organizations||[]).length, isEnterprise: s.state.zoConfig?.build_type, version: s.state.zoConfig?.version, theme: s.state.theme }; });
console.log(JSON.stringify(store));
await b.close();
